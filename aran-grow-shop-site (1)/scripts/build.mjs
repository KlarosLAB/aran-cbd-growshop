// Build step (also run by Netlify on every deploy):
//   1. packs the page template and browser scripts into netlify/lib/assets.mjs for the functions;
//   2. with --preview <file>, writes a static demo page (no payments, demo panel) from the seed catalogue.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const sharedJs = read("netlify/lib/shared.mjs").replace(/^export /gm, "");
const assets =
  "// Generated by scripts/build.mjs. Do not edit.\n" +
  `export const template = ${JSON.stringify(read("src/template.html"))};\n` +
  `export const appJs = ${JSON.stringify(read("src/app.js"))};\n` +
  `export const sharedJs = ${JSON.stringify(sharedJs)};\n`;
writeFileSync(join(root, "netlify/lib/assets.mjs"), assets);
console.log("assets.mjs", assets.length, "bytes");

const i = process.argv.indexOf("--preview");
if (i > -1) {
  const { renderPage } = await import("../netlify/lib/render.mjs");
  const { SEED } = await import("../netlify/lib/content.mjs");
  const html = renderPage({ items: SEED, reviews: [], siteUrl: "", live: false, base: "", route: { kind: "home" } });
  if (html.includes("%%")) throw new Error("unfilled token in page");
  writeFileSync(process.argv[i + 1], html);
  console.log("preview", process.argv[i + 1], html.length, "bytes");
}
